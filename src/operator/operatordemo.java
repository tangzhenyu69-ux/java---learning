package operator;

public class operatordemo {
    public static void main(String[] args) {
        int a = 15;
        int b = 4;
        System.out.println(a + b);
        System.out.println(a - b);
        System.out.println(a * b);
        System.out.println(a / b);
        System.out.println(a % b);//取余
        System.out.println("------------------");

        double c = 15.5;
        double d = 4.2;
        System.out.println(c + d);
        System.out.println(c - d);
        System.out.println(c * d);
        System.out.println(c / d);
        System.out.println(c % d);//取余
    }
}
